package remediation

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// FixMode determines how aggressive the autofix should be
type FixMode int

const (
	// FixModeSafe only applies fixes that cannot break functionality
	FixModeSafe FixMode = iota
	// FixModeReview generates patches for human review
	FixModeReview
)

// Fix represents a single remediation fix
type Fix struct {
	VulnType    string   `json:"vuln_type"`
	Target      string   `json:"target"`
	Description string   `json:"description"`
	FixType     string   `json:"fix_type"` // "config", "code", "docker", "firewall"
	Safe        bool     `json:"safe"`     // Can be auto-applied without breaking things
	Applied     bool     `json:"applied"`
	FilePath    string   `json:"file_path,omitempty"`
	Original    string   `json:"original,omitempty"`
	Patched     string   `json:"patched,omitempty"`
	Commands    []string `json:"commands,omitempty"` // Commands to run
	Error       string   `json:"error,omitempty"`
}

// FixResult contains the results of an autofix operation
type FixResult struct {
	Mode         FixMode   `json:"mode"`
	TotalVulns   int       `json:"total_vulns"`
	FixesApplied int       `json:"fixes_applied"`
	FixesPending int       `json:"fixes_pending"`
	Fixes        []*Fix    `json:"fixes"`
	StartTime    time.Time `json:"start_time"`
	EndTime      time.Time `json:"end_time"`
}

// AutoFixer handles automatic remediation
type AutoFixer struct {
	db        *Database
	mode      FixMode
	outputDir string
	fixes     []*Fix
	dryRun    bool
}

// NewAutoFixer creates a new auto-fixer
func NewAutoFixer(mode FixMode, outputDir string) *AutoFixer {
	return &AutoFixer{
		db:        NewDatabase(),
		mode:      mode,
		outputDir: outputDir,
		fixes:     make([]*Fix, 0),
		dryRun:    false,
	}
}

// SetDryRun enables dry-run mode (generate but don't apply)
func (af *AutoFixer) SetDryRun(dryRun bool) {
	af.dryRun = dryRun
}

// GenerateFixes analyzes vulnerabilities and generates fixes
func (af *AutoFixer) GenerateFixes(vulns []VulnInput) *FixResult {
	result := &FixResult{
		Mode:      af.mode,
		StartTime: time.Now(),
		Fixes:     make([]*Fix, 0),
	}

	for _, vuln := range vulns {
		fixes := af.generateFixesForVuln(vuln)
		result.Fixes = append(result.Fixes, fixes...)
	}

	result.TotalVulns = len(vulns)
	result.EndTime = time.Now()

	// Count applied vs pending
	for _, fix := range result.Fixes {
		if fix.Applied {
			result.FixesApplied++
		} else {
			result.FixesPending++
		}
	}

	return result
}

// VulnInput represents a vulnerability to fix
type VulnInput struct {
	Type        string `json:"type"`
	Target      string `json:"target"`
	Service     string `json:"service"`
	Description string `json:"description"`
	Evidence    string `json:"evidence"`
}

// generateFixesForVuln creates fixes for a single vulnerability
func (af *AutoFixer) generateFixesForVuln(vuln VulnInput) []*Fix {
	var fixes []*Fix

	switch {
	case strings.Contains(vuln.Type, "security_header") || strings.Contains(vuln.Type, "missing_header"):
		fixes = append(fixes, af.fixSecurityHeaders(vuln)...)
	case strings.Contains(vuln.Type, "redis_unauth"):
		fixes = append(fixes, af.fixRedisUnauth(vuln))
	case strings.Contains(vuln.Type, "mongodb_unauth"):
		fixes = append(fixes, af.fixMongoDBUnauth(vuln))
	case strings.Contains(vuln.Type, "ssh"):
		fixes = append(fixes, af.fixSSH(vuln))
	case strings.Contains(vuln.Type, "rpc_command_injection") || strings.Contains(vuln.Type, "command_injection"):
		fixes = append(fixes, af.fixCommandInjection(vuln))
	case strings.Contains(vuln.Type, "grpc"):
		fixes = append(fixes, af.fixGRPC(vuln))
	case strings.Contains(vuln.Type, "sql"):
		fixes = append(fixes, af.fixSQLInjection(vuln))
	case strings.Contains(vuln.Type, "info_disclosure"):
		fixes = append(fixes, af.fixInfoDisclosure(vuln))
	case strings.Contains(vuln.Type, "ftp_anonymous"):
		fixes = append(fixes, af.fixFTPAnonymous(vuln))
	case strings.Contains(vuln.Type, "default_credentials"):
		fixes = append(fixes, af.fixDefaultCredentials(vuln))
	}

	return fixes
}

// fixSecurityHeaders generates fixes for missing security headers
func (af *AutoFixer) fixSecurityHeaders(vuln VulnInput) []*Fix {
	var fixes []*Fix

	// This is SAFE - adding headers doesn't break functionality
	nginxConfig := `# Security Headers - Auto-generated by PentestAI
add_header X-Content-Type-Options "nosniff" always;
add_header X-Frame-Options "DENY" always;
add_header X-XSS-Protection "1; mode=block" always;
add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
add_header Content-Security-Policy "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Permissions-Policy "geolocation=(), microphone=(), camera=()" always;
`

	apacheConfig := `# Security Headers - Auto-generated by PentestAI
Header always set X-Content-Type-Options "nosniff"
Header always set X-Frame-Options "DENY"
Header always set X-XSS-Protection "1; mode=block"
Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"
Header always set Content-Security-Policy "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
`

	fix := &Fix{
		VulnType:    vuln.Type,
		Target:      vuln.Target,
		Description: "Add missing security headers to web server",
		FixType:     "config",
		Safe:        true, // Headers don't break functionality
		FilePath:    filepath.Join(af.outputDir, "patches", "security-headers-nginx.conf"),
		Patched:     nginxConfig,
	}

	if af.mode == FixModeSafe && !af.dryRun {
		if err := af.writePatchFile(fix.FilePath, nginxConfig); err != nil {
			fix.Error = err.Error()
		} else {
			fix.Applied = true
		}
	}
	fixes = append(fixes, fix)

	// Also generate Apache version
	apacheFix := &Fix{
		VulnType:    vuln.Type,
		Target:      vuln.Target,
		Description: "Add missing security headers (Apache version)",
		FixType:     "config",
		Safe:        true,
		FilePath:    filepath.Join(af.outputDir, "patches", "security-headers-apache.conf"),
		Patched:     apacheConfig,
	}

	if af.mode == FixModeSafe && !af.dryRun {
		if err := af.writePatchFile(apacheFix.FilePath, apacheConfig); err != nil {
			apacheFix.Error = err.Error()
		} else {
			apacheFix.Applied = true
		}
	}
	fixes = append(fixes, apacheFix)

	return fixes
}

