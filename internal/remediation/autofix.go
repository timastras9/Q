// writePatchFile writes a patch file to disk
func (af *AutoFixer) writePatchFile(path, content string) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0644)
}

// GenerateReport creates a human-readable fix report
func (af *AutoFixer) GenerateReport(result *FixResult) string {
	var sb strings.Builder

	sb.WriteString("╔══════════════════════════════════════════════════════════════╗\n")
	sb.WriteString("║              AUTOFIX REMEDIATION REPORT                      ║\n")
	sb.WriteString("╚══════════════════════════════════════════════════════════════╝\n\n")

	sb.WriteString(fmt.Sprintf("Mode: %s\n", modeToString(result.Mode)))
	sb.WriteString(fmt.Sprintf("Generated: %s\n\n", result.EndTime.Format("2006-01-02 15:04:05")))

	sb.WriteString("═══ SUMMARY ═══\n")
	sb.WriteString(fmt.Sprintf("Total Vulnerabilities: %d\n", result.TotalVulns))
	sb.WriteString(fmt.Sprintf("Fixes Generated: %d\n", len(result.Fixes)))
	sb.WriteString(fmt.Sprintf("Auto-Applied (Safe): %d\n", result.FixesApplied))
	sb.WriteString(fmt.Sprintf("Pending Review: %d\n\n", result.FixesPending))

	// Group by safe/review needed
	var safeFixes, reviewFixes []*Fix
	for _, fix := range result.Fixes {
		if fix.Safe {
			safeFixes = append(safeFixes, fix)
		} else {
			reviewFixes = append(reviewFixes, fix)
		}
	}

	if len(safeFixes) > 0 {
		sb.WriteString("═══ SAFE FIXES (Auto-Applied) ═══\n")
		for _, fix := range safeFixes {
			status := "✓ APPLIED"
			if fix.Error != "" {
				status = "✗ ERROR: " + fix.Error
			} else if !fix.Applied {
				status = "○ GENERATED"
			}
			sb.WriteString(fmt.Sprintf("\n[%s] %s\n", status, fix.Description))
			sb.WriteString(fmt.Sprintf("   Target: %s\n", fix.Target))
			sb.WriteString(fmt.Sprintf("   File: %s\n", fix.FilePath))
		}
		sb.WriteString("\n")
	}

	if len(reviewFixes) > 0 {
		sb.WriteString("═══ FIXES REQUIRING REVIEW ═══\n")
		sb.WriteString("These fixes could break functionality - review before applying!\n")
		for _, fix := range reviewFixes {
			sb.WriteString(fmt.Sprintf("\n[REVIEW] %s\n", fix.Description))
			sb.WriteString(fmt.Sprintf("   Target: %s\n", fix.Target))
			sb.WriteString(fmt.Sprintf("   Type: %s\n", fix.FixType))
			sb.WriteString(fmt.Sprintf("   File: %s\n", fix.FilePath))
			if len(fix.Commands) > 0 {
				sb.WriteString("   Apply with:\n")
				for _, cmd := range fix.Commands {
					sb.WriteString(fmt.Sprintf("     %s\n", cmd))
				}
			}
		}
		sb.WriteString("\n")
	}

	sb.WriteString("═══ NEXT STEPS ═══\n")
	sb.WriteString("1. Review all generated patches in: " + af.outputDir + "/patches/\n")
	sb.WriteString("2. Test patches in a staging environment first\n")
	sb.WriteString("3. Apply safe fixes to production\n")
	sb.WriteString("4. Schedule maintenance window for review-required fixes\n")
	sb.WriteString("5. Re-run autopwn to verify fixes\n")

	return sb.String()
}

func modeToString(mode FixMode) string {
	switch mode {
	case FixModeSafe:
		return "SAFE (auto-apply non-breaking fixes)"
	case FixModeReview:
		return "REVIEW (generate all fixes for human review)"
	default:
		return "UNKNOWN"
	}
}
